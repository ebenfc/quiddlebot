#!/bin/sh
# Builds QuiddleBot/Resources/words.txt, the word list behind the counter's word check:
# ENABLE1 (public domain) plus scripts/wordlist/additions.txt, lowercase a-z only, 2 to 15
# letters, deduplicated and sorted. Deterministic, so running it twice changes nothing.
#
# Usage: scripts/build-wordlist.sh path/to/enable1.txt
# ENABLE1 is not committed (1.7 MB, frozen, public domain). Known mirrors:
#   https://raw.githubusercontent.com/dolph/dictionary/master/enable1.txt
#   https://norvig.com/ngrams/enable1.txt
# The sha256 check below makes sure it is the file we expect.
# After the first run, `xcodegen generate` so words.txt joins the project.
set -eu
cd "$(dirname "$0")/.."
in=${1:?usage: scripts/build-wordlist.sh path/to/enable1.txt}
expected=3f16130220645692ed49c7134e24a18504c2ca55b3c012f7290e3e77c63b1a89
if command -v sha256sum >/dev/null 2>&1; then
  actual=$(sha256sum "$in" | cut -d' ' -f1)
else
  actual=$(shasum -a 256 "$in" | cut -d' ' -f1)
fi
[ "$actual" = "$expected" ] || { echo "$in is not the ENABLE1 list this script expects (sha256 $actual)"; exit 1; }

out=QuiddleBot/Resources/words.txt
mkdir -p "$(dirname "$out")"
{
  echo "# QuiddleBot word list. Generated by scripts/build-wordlist.sh; do not edit by hand."
  echo "# ENABLE1 (Enhanced North American Benchmark Lexicon, public domain) plus scripts/wordlist/additions.txt."
  cat "$in" scripts/wordlist/additions.txt \
    | tr -d '\r' \
    | sed 's/#.*//' \
    | tr '[:upper:]' '[:lower:]' \
    | tr -d ' \t' \
    | grep -E '^[a-z]{2,15}$' \
    | LC_ALL=C sort -u
} > "$out"
n=$(grep -vc '^#' "$out")
[ "$n" -gt 168000 ] || { echo "only $n words in $out; something went wrong"; exit 1; }
echo "wrote $out: $n words"
